"""fp32 audio reference for EmbeddingGemma 2, audio fp16 overflow map, and text<->audio checks.

    uv run --no-project --python 3.11 --with transformers==5.19.0 --with torch==2.9.0 \
        --with "sentence-transformers>=6.1" --with pillow --with torchvision python make_audio_reference.py

Clips (16 kHz mono WAV in fixtures/audio/, regenerated by this script):
    speech from macOS `say` (kept local, not committed), and synthetic tone / noise / chirp (committed).
Writes:
    fixtures/audio_reference.json   per clip: caption, samples, mel frames, audio tokens, seq length,
                                    fp32 768-d embedding, caption embedding; mel features of two clips
    fixtures/audio_overflow.json    per-module max |activation| (audio tower, embedder, text on audio)
"""

import json
import subprocess
import tempfile
import wave
from pathlib import Path

import numpy as np
import torch
from sentence_transformers import SentenceTransformer

MODEL_ID = "google/embeddinggemma-2"
REVISION = "914f7f89142e33e77833254d9c9b90c3cef7303b"
FIX = Path(__file__).resolve().parent / "fixtures"
AUD = FIX / "audio"
SR = 16000

SPEECH = [  # stem, voice, spoken text, caption used as a text query
    ("speech_weather", "Samantha", "Tomorrow will be sunny and warm, with a light breeze in the afternoon.",
     "a weather forecast for a sunny day"),
    ("speech_recipe", "Daniel", "Mix two cups of flour with one egg, then bake the bread for forty minutes.",
     "instructions for baking bread"),
    ("speech_train", "Karen", "The train to the airport leaves from platform four in ten minutes.",
     "an announcement about a train departure"),
    ("speech_football", "Samantha", "What a goal! The striker scored in the last minute and the crowd went wild.",
     "a sports commentator describing a goal"),
    ("speech_doctor", "Daniel", "Please take one tablet twice a day with food, and drink plenty of water.",
     "a doctor giving medicine instructions"),
]
LONG_SPEECH = ("speech_long_story", "Samantha",
               "Once upon a time, in a small village by the sea, there lived an old fisherman. Every morning he "
               "rowed his little boat past the lighthouse, cast his nets, and waited patiently for the tide. One "
               "stormy evening, the waves grew tall and the wind howled, but the light from the tower guided him "
               "safely home, where his family waited by the fire with warm soup and fresh bread.",
               "a story about a fisherman and a lighthouse")
SYNTH = [  # stem, caption
    ("tone_440hz", "a steady high pitched beep"),
    ("white_noise", "static white noise"),
    ("chirp_rising", "a tone sweeping up in pitch"),
]


def write_wav(path: Path, x: np.ndarray) -> None:
    with wave.open(str(path), "wb") as w:
        w.setnchannels(1)
        w.setsampwidth(2)
        w.setframerate(SR)
        w.writeframes((np.clip(x, -1, 1) * 32767).astype("<i2").tobytes())


def read_wav(path: Path) -> np.ndarray:
    with wave.open(str(path), "rb") as w:
        assert w.getframerate() == SR and w.getnchannels() == 1 and w.getsampwidth() == 2
        return np.frombuffer(w.readframes(w.getnframes()), dtype="<i2").astype(np.float32) / 32768.0


def make_speech(stem: str, voice: str, text: str) -> Path:
    path = AUD / f"{stem}.wav"
    with tempfile.TemporaryDirectory() as d:
        aiff = Path(d) / "s.aiff"
        if subprocess.run(["say", "-v", voice, "-o", str(aiff), text], capture_output=True).returncode != 0:
            subprocess.run(["say", "-o", str(aiff), text], check=True)
        subprocess.run(["ffmpeg", "-y", "-loglevel", "error", "-i", str(aiff), "-ac", "1", "-ar", str(SR),
                        "-sample_fmt", "s16", str(path)], check=True)
    return path


def make_synth(stem: str) -> Path:
    t = np.arange(int(3.0 * SR)) / SR
    rng = np.random.default_rng(0)
    x = {"tone_440hz": 0.3 * np.sin(2 * np.pi * 440 * t),
         "white_noise": 0.2 * rng.standard_normal(len(t)),
         "chirp_rising": 0.3 * np.sin(2 * np.pi * (200 * t + (2000 - 200) / (2 * 3.0) * t * t))}[stem]
    path = AUD / f"{stem}.wav"
    write_wav(path, x)
    return path


def main() -> None:
    AUD.mkdir(parents=True, exist_ok=True)
    clips = [(stem, make_speech(stem, v, text), cap) for stem, v, text, cap in SPEECH + [LONG_SPEECH]]
    clips += [(stem, make_synth(stem), cap) for stem, cap in SYNTH]

    model = SentenceTransformer(MODEL_ID, revision=REVISION, device="cpu",
                                model_kwargs={"torch_dtype": torch.float32}, config_kwargs={"vision_config": None})
    model.eval()
    hf_model, processor = model[0].model, model[0].processor

    stats: dict[str, dict[str, float]] = {}

    def record(name, key, t):
        if isinstance(t, (tuple, list)):
            t = t[0]
        if hasattr(t, "last_hidden_state"):
            t = t.last_hidden_state
        if torch.is_tensor(t) and t.is_floating_point() and t.numel():
            s = stats.setdefault(name, {})
            s[key] = max(s.get(key, 0.0), float(t.detach().abs().max()))

    for prefix, root in (("audio.", hf_model.audio_tower), ("embed_audio.", hf_model.embed_audio),
                         ("text.", hf_model.language_model)):
        for name, mod in root.named_modules():
            def hook(mod, inp, out, name=prefix + name):
                record(name, "out", out)
                if ("Norm" in type(mod).__name__) and inp:
                    record(name, "in", inp[0])
            mod.register_forward_hook(hook)

    items, mel_examples = [], {}
    for stem, path, caption in clips:
        x = read_wav(path)
        inputs = processor(text=["<|audio|>"], audio=[x], sampling_rate=SR, return_tensors="pt")
        with torch.no_grad():
            out = hf_model(**inputs)
        m = inputs["attention_mask"][0].float()
        v = (out.last_hidden_state[0] * m[:, None]).sum(0) / m.sum()
        v = (v / v.norm()).numpy()
        v_st = model.encode([{"audio": {"array": x, "sampling_rate": SR}}], convert_to_numpy=True, normalize_embeddings=True)[0]
        n_tok = int((inputs["input_ids"][0] == hf_model.config.audio_token_id).sum())
        mel_frames = int(inputs["input_features_mask"][0].sum())
        cap = model.encode([caption], convert_to_numpy=True, normalize_embeddings=True)[0]
        print(f"{stem:20s} {len(x) / SR:5.2f} s  mel {mel_frames:4d} (padded {inputs['input_features'].shape[1]})  "
              f"tokens {n_tok:3d}  seq {int(m.sum()):4d}  cos(manual, ST) {float(np.dot(v, v_st)):.6f}  "
              f"cos(caption) {float(np.dot(v, cap)):.3f}")
        items.append({"stem": stem, "caption": caption, "committed": not stem.startswith("speech"),
                      "samples": len(x), "mel_frames": mel_frames, "audio_tokens": n_tok,
                      "seq_len": int(m.sum()), "input_ids": inputs["input_ids"][0].tolist(),
                      "embedding": [round(float(t), 7) for t in v],
                      "caption_embedding": [round(float(t), 7) for t in cap]})
        if stem in ("tone_440hz", "chirp_rising"):
            mel_examples[stem] = inputs["input_features"][0, :mel_frames].numpy().round(5).tolist()

    emb = np.array([it["embedding"] for it in items])
    caps = np.array([it["caption_embedding"] for it in items])
    sim = caps @ emb.T
    print(f"text->audio top-1: {(sim.argmax(1) == np.arange(len(items))).mean():.2f}  "
          f"(per clip best: {[items[j]['stem'] for j in sim.argmax(1)]})")
    (FIX / "audio_reference.json").write_text(json.dumps(
        {"items": items, "mel_examples": mel_examples, "caption_audio_sim": sim.round(4).tolist()}))
    (FIX / "audio_overflow.json").write_text(json.dumps({"modules": stats}, indent=1))
    for group in ("audio.", "embed_audio.", "text."):
        mods = {n: s for n, s in stats.items() if n.startswith(group)}
        norms = [(s["in"], n) for n, s in mods.items() if "in" in s]
        print(f"{group} max {max(max(s.values()) for s in mods.values()):.1f}; norm inputs >256: "
              f"{sum(v > 256 for v, _ in norms)}/{len(norms)}; >65504: {sum(v > 65504 for v, _ in norms)}; "
              f"top: {sorted(norms, reverse=True)[:3]}")


if __name__ == "__main__":
    main()
